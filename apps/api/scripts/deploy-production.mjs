// Deploys the billing API to Cloudflare in PRODUCTION mode (TON mainnet, real payments).
//
//   node apps/api/scripts/deploy-production.mjs --key-file <file with TONAPI_KEY=...>
//   (or set TONAPI_KEY in the environment)
//
// Steps: Cloudflare login (browser) → D1 database (created once) → migrations →
// TONAPI_KEY secret → Worker deploy → health check → writes the API URL into
// packages/shared/src/production.ts so the website and the extension use it.
// Safe to run again: every step is idempotent. The key is never printed or written to the repo.
import { spawn, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const API = resolve(import.meta.dirname, '..');
const ROOT = resolve(API, '../..');
const PROD_TS = join(ROOT, 'packages/shared/src/production.ts');
const PROD_CONFIG = join(API, 'wrangler.production.toml');
const DB_NAME = 'quickreply-billing';
const USDT_MAINNET = 'EQCxE6mUtQJKFnGfaROTKOt1lZbDiiX1kCixRv7Nw2Id_sDs';

const step = (m) => console.log(`\n== ${m}`);
const fail = (m) => {
  console.error(`\n[!] ${m}`);
  process.exit(1);
};

// Interactive (browser login, prompts) — output goes straight to the console.
function interactive(args, extraEnv = {}) {
  const r = spawnSync(`npx wrangler ${args}`, { cwd: API, shell: true, stdio: 'inherit', env: { ...process.env, ...extraEnv } });
  return r.status === 0;
}

// Captured, but still shown, so any prompt is visible.
function captured(args, { input, extraEnv = {}, quiet = false } = {}) {
  return new Promise((ok) => {
    const p = spawn(`npx wrangler ${args}`, { cwd: API, shell: true, env: { ...process.env, ...extraEnv }, stdio: [input === undefined ? 'inherit' : 'pipe', 'pipe', 'pipe'] });
    let out = '';
    p.stdout.on('data', (d) => {
      out += d;
      if (!quiet) process.stdout.write(d);
    });
    p.stderr.on('data', (d) => {
      out += d;
      if (!quiet) process.stderr.write(d);
    });
    if (input !== undefined) p.stdin.end(input);
    p.on('close', (code) => ok({ code, out }));
  });
}

function readKey() {
  const i = process.argv.indexOf('--key-file');
  if (i > 0 && process.argv[i + 1]) {
    const m = /^\s*TONAPI_KEY\s*=\s*"?([^"\r\n]+)"?\s*$/m.exec(readFileSync(process.argv[i + 1], 'utf8'));
    if (m) return m[1].trim();
    fail(`No TONAPI_KEY=... line in ${process.argv[i + 1]}`);
  }
  if (process.env.TONAPI_KEY) return process.env.TONAPI_KEY.trim();
  fail('Pass --key-file <file> or set TONAPI_KEY (TON Console API key).');
}

function siteUrl() {
  const m = /siteUrl:\s*'([^']+)'/.exec(readFileSync(PROD_TS, 'utf8'));
  return m[1].replace(/\/$/, '');
}

async function main() {
  const key = readKey();
  const site = siteUrl();

  step('Cloudflare account');
  const who = await captured('whoami', { quiet: true });
  if (who.code !== 0 || /not authenticated/i.test(who.out)) {
    console.log('A browser window will open: sign in to Cloudflare and click "Allow".');
    if (!interactive('login')) fail('Cloudflare login failed.');
  }
  console.log('Signed in.');

  step('D1 database');
  const list = async () => {
    const r = await captured('d1 list --json', { quiet: true, extraEnv: { CI: '1' } });
    try {
      const start = r.out.search(/^\[/m);
      const arr = JSON.parse(r.out.slice(start));
      return arr.find((d) => d.name === DB_NAME)?.uuid ?? null;
    } catch {
      return null;
    }
  };
  let dbId = await list();
  if (!dbId) {
    const r = await captured(`d1 create ${DB_NAME}`, { extraEnv: { CI: '1' } });
    if (r.code !== 0) fail('Could not create the D1 database.');
    dbId = (await list()) ?? /([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/.exec(r.out)?.[1] ?? null;
  }
  if (!dbId) fail('Could not find the D1 database id.');
  console.log(`${DB_NAME}: ${dbId}`);

  // Production config, generated from wrangler.toml (not committed).
  let toml = readFileSync(join(API, 'wrangler.toml'), 'utf8');
  const set = (k, v) => {
    const re = new RegExp(`^${k}\\s*=.*$`, 'm');
    if (!re.test(toml)) fail(`wrangler.toml has no ${k}`);
    toml = toml.replace(re, `${k} = ${JSON.stringify(v)}`);
  };
  set('database_id', dbId);
  set('TON_NETWORK', 'mainnet');
  set('USDT_MASTERS', USDT_MAINNET);
  set('TEST_PRICE_DIVISOR', '1');
  set('ALLOWED_ORIGINS', `${site},chrome-extension://*`);
  toml = toml.replace(/^main = .*$/m, (l) => `${l}\nworkers_dev = true`);
  writeFileSync(PROD_CONFIG, `# GENERATED by scripts/deploy-production.mjs — do not edit or commit.\n${toml}`);

  step('Database tables');
  if ((await captured(`d1 migrations apply ${DB_NAME} --remote -c wrangler.production.toml`, { extraEnv: { CI: '1' } })).code !== 0) fail('Migrations failed.');

  step('Worker');
  const outDir = mkdtempSync(join(tmpdir(), 'qr-deploy-'));
  const outFile = join(outDir, 'out.ndjson');
  const dep = await captured('deploy -c wrangler.production.toml', { extraEnv: { WRANGLER_OUTPUT_FILE_PATH: outFile } });
  if (dep.code !== 0) fail('Deploy failed. If it asked to register a workers.dev subdomain, do that in the Cloudflare dashboard (Workers & Pages) and run this again.');
  let url = null;
  try {
    for (const line of readFileSync(outFile, 'utf8').split('\n').filter(Boolean)) {
      const e = JSON.parse(line);
      const t = (e.targets ?? []).find((u) => /workers\.dev/.test(u)) ?? e.targets?.[0];
      if (e.type === 'deploy' && t) url = t;
    }
  } catch {
    /* fall back to the console output */
  }
  rmSync(outDir, { recursive: true, force: true });
  url ??= /https:\/\/[a-z0-9.-]+\.workers\.dev/.exec(dep.out)?.[0] ?? null;
  if (!url) fail('Deployed, but the Worker URL was not found in the output.');
  url = url.replace(/\/$/, '');

  step('TonAPI key (secret)');
  if ((await captured('secret put TONAPI_KEY -c wrangler.production.toml', { input: key, extraEnv: { CI: '1' } })).code !== 0) fail('Could not set the TONAPI_KEY secret.');

  step('Health check');
  let cfg = null;
  for (let i = 0; i < 20 && !cfg; i++) {
    try {
      const r = await fetch(`${url}/v1/config`);
      if (r.ok) cfg = await r.json();
    } catch {
      /* propagating */
    }
    if (!cfg) await new Promise((r) => setTimeout(r, 3000));
  }
  if (!cfg) fail(`${url}/v1/config does not answer yet. Run this script again in a minute.`);
  console.log(`network: ${cfg.network}, test mode: ${cfg.testMode}, currencies: ${cfg.currencies.join(', ')}, wallet: ${cfg.payTo}`);
  if (cfg.testMode) fail('The API is still in test mode.');
  if (!cfg.currencies.includes('USDT')) console.log('[warning] USDT is not enabled yet (our USDT wallet could not be resolved via TonAPI). TON payments work; run again later.');

  const ts = readFileSync(PROD_TS, 'utf8').replace(/billingApi:\s*'[^']*'/, `billingApi: '${url}'`);
  writeFileSync(PROD_TS, ts);
  console.log(`\nBilling API is live: ${url}`);
  console.log('Saved to packages/shared/src/production.ts');
}

main().catch((e) => fail(e.message));
